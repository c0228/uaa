<div>The commercial varieties you can produce from your raw bentonite, arranged 
from <b>lowest investment (mechanical processing)</b> to <b>highest value-add (chemical modification)</b>.</div>

<div class="mtop15p">
	<div><h5><b>Tier 1: Mechanical Processing Only (Crushing, Drying & Grinding)</b></h5></div>
	<div><i><b>Requires:</b> Sun-drying yard, jaw crusher, Raymond mill/pulverizer, and vibrating screens.</i></div>
	<div class="list-group">
		<!-- -->
		<div class="list-group-item mtop15p">
			<div><b><span class="uppercase">1. Industrial Bentonite Powder</span> (200 to 325 Mesh)</b></div>
			<ul>
				<li class="mtop5p"><b>How to make:</b> Dry raw lumps to ~10–12% moisture and grind in a pulverizer.</li>
				<li class="mtop5p"><b>Who buys it:</b> Piling/foundation contractors, civil engineers, iron ore pellet plants, and waterproofing suppliers.</li>
			</ul>
		</div>
		<!-- -->
		<!-- -->
		<div class="list-group-item mtop15p">
			<div><b><span class="uppercase">2. Clumping Cat Litter Granules</span> (1–4 mm)</b></div>
			<ul>
				<li class="mtop5p">
					<div><b>How to make:</b> Crush dried clay using a roller crusher and screen out fine dust to leave uniform 1–4 mm granules.</div>
					<div><i>(<u>Optional</u>: Spray with 0.5–1% fragrance or blend with zeolite/activated carbon for odor control).</i></div></li>
				<li class="mtop5p"><b>Who buys it:</b> Pet care brands, supermarkets, and export markets (high retail margin).</li>
			</ul>
		</div>
		<!-- -->
