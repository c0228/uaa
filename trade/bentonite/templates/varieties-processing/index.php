			<ul>
				<li class="mtop5p"><b>How to make:</b> Compress slightly moist bentonite powder through a pellet mill or extruder and dry hard.</li>
				<li class="mtop5p"><b>Who buys it:</b> Borewell drillers and geotechnical engineers (used to plug/seal deep wells).</li>
