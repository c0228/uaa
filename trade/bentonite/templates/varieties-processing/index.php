		<div class="list-group-item mtop15p">
			<div><b><span class="uppercase">3. Agrochemical / Pesticide Carrier Granules</span> (16/30 or 30/60 Mesh)</b></div>
			<ul>
				<li class="mtop5p"><b>How to make:</b> Crush, screen to uniform micro-granules, and lightly calcine 
				(heat-treat) so the granules don't turn into mud when sprayed with liquid pesticides.</li>
				<li class="mtop5p"><b>Who buys it:</b> Fertilizer and crop protection companies.</li>
			</ul>
