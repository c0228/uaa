<div class="mtop15p">
	<div><h5><b>Tier 2: Light Chemical Activation (Low-to-Medium Investment)</b></h5></div>
	<div><i><b>Requires:</b> Muller mixer / pug mill, dosing system, and drying setup.</i></div>
	<div class="list-group">
		<div class="list-group-item mtop15p">
			<div><b><span class="uppercase">6. Sodium-Activated Bentonite (Foundry & Drilling Grade)</span></b></div>
			<ul>
				<li class="mtop5p"><b>How to make:</b> If your raw clay is <b>Calcium Bentonite</b> (low swelling), knead it with <b>2% to 5% Soda Ash 
				(Sodium Carbonate)</b> and ~25–30% water in a muller mixer, cure in piles for 3–7 days, then dry and grind.</li>
				<li class="mtop5p"><b>Result:</b> Swelling jumps from ~8 mL to 25–30+ mL</li>
				<li class="mtop5p"><b>Who buys it:</b> Metal foundries (cast iron/steel) and oil/water well drillers (API/OCMA grade).</li>
			</ul>
		</div>
		<div class="list-group-item">
			<div class="list-group-item mtop15p">
				<div><b><span class="uppercase">7. Polymer-Extended Drilling Bentonite</span></b></div>
				<ul>
					<li class="mtop5p"><b>How to make:</b> Dry-blend sodium bentonite powder with <b>0.2% to 1% anionic polymers</b> (like PAC – Polyanionic Cellulose or PHPA).</li>
					<li class="mtop5p"><b>Result:</b> Dramatically boosts viscosity and reduces fluid loss to meet strict API 13A oilfield specs even from average-grade clay.</li>
					<li class="mtop5p"><b>Who buys it:</b> Oil & gas drilling companies and Horizontal Directional Drilling (HDD) contractors.</li>
				</ul>
			</div>
		</div>
		<div class="list-group-item">
			<div class="list-group-item mtop15p">
				<div><b><span class="uppercase">8. Mycotoxin Binder (Animal Feed Grade)</span></b></div>
				<ul>
					<li class="mtop5p"><b>How to make:</b> Select clean, low-heavy-metal calcium bentonite, finely grind (300+ mesh), and optionally blend with yeast cell walls or organic acids.</li>
					<li class="mtop5p"><b>Who buys it:</b> Poultry, dairy, and aquaculture feed mills (huge demand in hubs like Telangana, Andhra Pradesh, and Tamil Nadu).</li>
				</ul>
			</div>
		</div>
	</div>
