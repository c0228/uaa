<div class="mtop15p"><h5><b>By End-Use & Regulatory Standards (Commercial Grade)</b></h5></div>
<div class="mtop15p">Global buyers buy bentonite based on strict laboratory test parameters rather than geological names:</div>
<ul>
	<li class="mtop5p"><b><u>API 13A Grade</u>:</b> Meets <b>American Petroleum Institute standards</b> for viscosity and fluid loss in oil/gas drilling.</li>
	<li class="mtop5p"><b><u>OCMA Grade</u>:</b> Meets <b>Oil Companies Materials Association standards</b> (slightly different fluid-loss and yield specs than API).</li>
	<li class="mtop5p"><b><u>Foundry Grade</u>:</b> Classified by <b>Green Compression Strength, Dry Strength,</b> and <b>Wet Tensile Strength</b> (how well it holds metal molds together under extreme heat).</li>
	<li class="mtop5p"><b><u>Pelletizing Grade</u>:</b> Classified by <b> Balling Index</b> and <b>Drop Number</b> (how well iron ore pellets survive falling onto conveyor belts without cracking).</li>
	<li class="mtop5p"><b><u>USP (United States Pharmacopeia) / BP (British Pharmacopoeia) / EP (European Pharmacopoeia) Grade</u>:</b> Meets US, British, or European Pharmacopoeia standards for heavy metal limits and microbial purity in medicines and cosmetics.</li>
</ul>
