	<div><h5><b>HS code (Harmonized System code)</b></h5></div>
	<div>HS code is an internationally standardized, six-digit numerical classification system maintained 
	by the World Customs Organization (WCO) to identify traded goods. Over 200 countries use it for customs 
	tariffs, trade rules, and import-export statistics.</div>
	<div class="mtop15p"><h5><b>How the Code Is Structured?</b></h5></div>
	<ul>
		<li><b>First 2 digits (Chapter):</b> Broad product category (e.g., 08 for edible fruit and nuts).</li>
		<li><b>Next 2 digits (Heading):</b> More specific group within that chapter (e.g., 04 for citrus or tropical fruits).</li>
		<li><b>Last 2 digits (Subheading):</b> Detailed product specification (e.g., 50 for mangoes, making 080450).</li>
		<li><b>Country extensions:</b> Many countries add extra digits for local tariffs and taxes — 
			such as 8-digit ITC-HS/HSN codes in India or 10-digit HTS/Schedule B codes in the U.S</li>
	</ul>
