<div align="center" class="uppercase mtop15p"><h5><b>Saudi Arabia <sup><code class="code-bg">12-digits</code></sup></b></h5></div>
<div class="list-group">
	<div class="list-group-item bg-grey">
		<span class="badge bg-secondary">HS Code</span> is maintained by the <b>ZATCA</b>
	</div>
</div>

<div class="mtop15p"><b>ZATCA</b> (the Government Authority) and <b>SABER</b> handle two separate steps of importing into Saudi Arabia: tax clearance and product safety.</div>
<div class="mtop15p">They both shares same 12-digit HS code to connect your safety approvals directly to your customs declaration.</div>
<blockquote class="mtop15p">
	<div class="mtop15p">
		<b>International Base (First 6 Digits):</b> Maintained globally by the World Customs Organization (WCO).
	</div>
	<div class="mtop15p">
		<b>Regional Alignment (Digits 7–8):</b> Aligned with the Gulf Cooperation Council (GCC) Unified Customs Tariff.
	</div>
	<div class="mtop15p">
		<b>National Breakdown (Digits 9–12):</b> Maintained and updated locally by ZATCA to set specific Saudi import duties, 
		VAT rules, and product restrictions.
	</div>
</blockquote>
<div class="list-group">
	<div class="list-group-item bg-grey">
		<i><u>Note</u>: Platforms like <b>SABER</b> and <b>Fasah</b> pull directly from ZATCA's official 12-digit tariff database so importers 
		and exporters always use the same code</i>
	</div>
</div>
