 <div align="center" class="uppercase mtop15p"><h5><b>India <sup><code class="code-bg">8-digits</code></sup></b></h5></div>
 <div class="list-group">
 <div class="list-group-item bg-grey"><b>HS Code</b> is maintained by the <b>DGFT (Directorate General of Foreign Trade)</b>.</div>
 </div>
 <div class="mtop15p"><b>ITC-HS Code (Indian Trade Clarification based on Harmonized System)</b> is India’s 8-digit classification system 
 for traded goods.</div>
 
 <blockquote style="padding:15px;margin-top:15px;">
	<div><b><u>Structure</u>:</b></div>
	<div class="mtop15p"><code><b>6-digits</b></code> set by 
	World Customs Organization (WCO) and <code><b>2-digits</b></code> are India-specific digits which determine Indian customs duty rates, GST slabs, 
	import/export restrictions, and export incentives like RoDTEP (Remission of Duties and Taxes on Exported Products).</div>
	<div class="mtop15p"><b><u>Schedules</u>:</b></div>
	<div class="mtop15p">Schedule I covers import policies and Schedule II covers export policies.</div>
 </blockquote>

