<div class="mtop15p"><h5><b>Backup plans for every workflow stage</b></h5></div>
	<!-- Stage 1: Supplier and production -->
	<div class="mtop15p"><b>Stage 1: Supplier and production</b></div>
	<div class="table-responsive">
	  <table class="table">
		<thead><tr><td><b>#</b></td><td><b>Failure scenario</b></td><td><b>Backup plan</b></td></tr></thead>
		<tbody>
			<tr><td>1.</td><td>Supplier fails to complete production</td><td>Activate an alternative approved supplier</td></tr>
			<tr><td>2.</td><td>Supplier delays production</td><td>Give a grace period, then activate backup supplier</td></tr>
			<tr><td>3.</td><td>Goods do not meet specifications</td><td>Reject batch and request replacement</td></tr>
			<tr><td>4.</td><td>Supplier cannot provide required quantity</td><td>Split order between multiple suppliers, subject to buyer approval</td></tr>
			<tr><td>5.</td><td>Supplier suddenly increases price</td><td>Enforce agreed purchase price or renegotiate with buyer</td></tr>
			<tr><td>6.</td><td>Supplier refuses shipment</td><td>Activate alternate supplier and enforce contractual remedies where applicable</td></tr>
		</tbody>
	  </table>
	</div>
	<div class="list-group">
		<div class="list-group-item" style="background-color:#f5f5f5;">
			<b>Note:</b> HurrayMarket should maintain at least two approved suppliers for every high-demand product wherever possible.
		</div>
	</div>
	<!-- Stage 2: Inspection and quality verification -->
	<div class="mtop15p"><b>Stage 2: Inspection and quality verification</b></div>
	<div class="table-responsive">
	  <table class="table">
		<thead><tr><td><b>#</b></td><td><b>Failure scenario</b></td><td><b>Backup plan</b></td></tr></thead>
		<tbody>
			<tr><td>1.</td><td>Inspection agency does not respond</td><td>Send request to secondary inspection agency</td></tr>
			<tr><td>2.</td><td>Inspector does not arrive</td><td>Reschedule or deploy alternate inspector</td></tr>
			<tr><td>3.</td><td>Inspection agency cannot visit the location</td><td>Engage a locally available inspection partner</td></tr>
			<tr><td>4.</td><td>Sample collection fails</td><td>Arrange a new collection under agreed sampling procedures</td></tr>
			<tr><td>5.</td><td>Laboratory equipment failure</td><td>Transfer samples to an approved backup laboratory, where sample integrity permits</td></tr>
			<tr><td>6.</td><td>COA/test report delayed</td><td>Escalate to laboratory manager and activate alternate lab</td></tr>
			<tr><td>7.</td><td>Product fails quality inspection</td><td>Hold shipment; supplier replaces or reprocesses goods</td></tr>
			<tr><td>8.</td><td>Buyer rejects inspection report</td><td>Arrange independent third-party reinspection</td></tr>
			<tr><td>9.</td><td>Two inspection reports conflict</td><td>Appoint a mutually agreed independent referee laboratory</td></tr>
		</tbody>
	  </table>
	</div>
	<div class="list-group">
		<div class="list-group-item" style="background-color:#f5f5f5;">
			<b>Note:</b> HurrayMarket should maintain two inspection agencies and two laboratories in every major sourcing region. 
			Do not allow goods to move to shipment simply because an inspection partner has failed to respond.
		</div>
	</div>
	<!-- Stage 3: Freight forwarding and logistics -->
	<div class="mtop15p"><b>Stage 3: Freight forwarding and logistics</b></div>
	<div class="table-responsive">
	  <table class="table">
		<thead><tr><td><b>#</b></td><td><b>Failure scenario</b></td><td><b>Backup plan</b></td></tr></thead>
		<tbody>
			<tr><td>1.</td><td>Freight forwarder does not respond</td><td>Assign shipment to secondary freight forwarder</td></tr>
			<tr><td>2.</td><td>Container booking unavailable</td><td>Search alternative shipping lines</td></tr>
			<tr><td>3.</td><td>Container shortage</td><td>Check nearby ports, alternate equipment or alternate sailing dates</td></tr>
			<tr><td>4.</td><td>Vessel cancellation</td><td>Rebook on the next suitable vessel</td></tr>
			<tr><td>5.</td><td>Freight rates suddenly increase</td><td>Compare backup forwarder quotations and apply agreed pricing rules</td></tr>
			<tr><td>6.</td><td>Cargo pickup delayed</td><td>Engage alternate transporter</td></tr>
			<tr><td>7.</td><td>Truck breakdown</td><td>Deploy replacement truck</td></tr>
			<tr><td>8.</td><td>Port congestion</td><td>Consider alternate port, subject to cost and buyer approval</td></tr>
			<tr><td>9.</td><td>Shipment missed cutoff</td><td>Rebook next sailing and notify buyer</td></tr>
			<tr><td>10.</td><td>Cargo damaged during transit</td><td>Activate insurance claim and damage survey</td></tr>
		</tbody>
	  </table>
	</div>
	<div class="list-group">
		<div class="list-group-item" style="background-color:#f5f5f5;">
			<b>Note:</b> HurrayMarket should maintain three levels of logistics backup:
			<ol>
			  <li>Primary freight forwarder</li>
			  <li>Secondary freight forwarder</li>
			  <li>Emergency logistics partner</li>
			</ol>
		</div>
	</div>
