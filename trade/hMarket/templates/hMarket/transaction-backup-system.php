			<tr><td>5.</td><td>Export documents incorrect</td><td>Correct documents and resubmit through authorized channels</td></tr>
			<tr><td>6.</td><td>Customs examination ordered</td><td>Arrange examination and provide requested documentation</td></tr>
			<tr><td>7.</td><td>Customs clearance held</td><td>Escalate through the proper Customs process</td></tr>
			<tr><td>8.</td><td>Export restriction discovered</td><td>Stop shipment and obtain legal/regulatory clearance</td></tr>
		</tbody>
	  </table>
